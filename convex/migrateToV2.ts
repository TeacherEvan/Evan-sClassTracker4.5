export const runAllMigrations = internalAction({
  handler: async (ctx: any) => {
    const results = {
      users: await ctx.runAction(migrations.migrateUsers),
      students: await ctx.runAction(migrations.migrateStudents),
      classes: await ctx.runAction(migrations.migrateClasses),
      providers: await ctx.runAction(migrations.migrateProviders),
      locations: await ctx.runAction(migrations.migrateLocations),
    };
    return results;
  },
});

